import type { LearningJourney, JourneyStage, WordSeed, ExpressionSeed } from './journey-schema';
// Entirely original teaching material. Each stage introduces six lexical items and two expressions.
type StageInput = [
  string,
  string,
  string,
  number,
  string,
  string,
  string,
  WordSeed[],
  ExpressionSeed[],
  JourneyStage['listening'],
  JourneyStage['cloze'],
  JourneyStage['output'],
];
function stage([
  id,
  title,
  place,
  image,
  role,
  intro,
  introZh,
  words,
  expressions,
  listening,
  cloze,
  output,
]: StageInput): JourneyStage {
  return {
    id,
    title,
    place,
    image,
    role,
    intro,
    introZh,
    task: output.zh,
    words,
    expressions,
    listening,
    cloze,
    output,
  };
}
const listen = (
  line: string,
  zh: string,
  answer: string,
  other: string[],
  why: string,
): JourneyStage['listening'] => ({
  line,
  zh,
  question: '听到这句话，接下来应该做什么？',
  options: [answer, ...other],
  answer,
  why,
});
const gap = (
  before: string,
  answer: string,
  after: string,
  zh: string,
  why: string,
  alternatives: string[] = [],
): JourneyStage['cloze'] => ({ before, answer, after, zh, why, alternatives });
const say = (
  prompt: string,
  zh: string,
  answer: string,
  other: string[],
  reply: string,
  replyZh: string,
  why: string,
  equivalents: string[] = [],
): JourneyStage['output'] => ({
  prompt,
  zh,
  answer,
  options: [answer, ...other],
  reply,
  replyZh,
  why,
  equivalents,
});
